// Embeds ccr.js and the public registry into ../index.html between the CCR markers.
// Run after changing either:  node ccr/embed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const code = readFileSync(here('./ccr.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
const registry = JSON.parse(readFileSync(here('./registry.json'), 'utf8'));
const block = `<!-- CCR:BEGIN (generated by ccr/embed.mjs; do not edit here) -->
<script>${code}
window.CCR_REGISTRY = ${JSON.stringify(registry).replace(/<\//g, '<\\/')};</script>
<!-- CCR:END -->`;
const page = readFileSync(here('../index.html'), 'utf8');
const re = /<!-- CCR:BEGIN[\s\S]*?<!-- CCR:END -->/;
if (!re.test(page)) throw new Error('CCR markers not found in index.html');
writeFileSync(here('../index.html'), page.replace(re, () => block));
console.log(`Embedded ${registry.entries.length} registry entries.`);
